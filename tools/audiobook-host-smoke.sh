#!/usr/bin/env bash
set -euo pipefail
# Adapted from yetisoldier/sonix-audiobooks d93da3b (GPL-3.0); see OFFLINE_ADDITIONS.md.

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
PLAYER="$ROOT/sonix-player"
WORK="${SONIX_SMOKE_DIR:-$ROOT/build/audiobook-host-smoke}"
RUN="$WORK/run"
SD="$WORK/sd"
CONFIG="$WORK/device_config.ini"
ASOUND="$WORK/asound.conf"
DB="$SD/.local/audiobooks.db"
FIFO="$WORK/control"
STATUS="$WORK/control.status"
DISPLAY_FILE="$WORK/x-display"
PLAYER_PID=""
XVFB_PID=""
WINDOW=""

fail() {
	printf 'audiobook smoke test: %s\n' "$*" >&2
	exit 1
}

need() {
	command -v "$1" >/dev/null 2>&1 || fail "missing required command: $1"
}

stop_player() {
	if [[ -n "$PLAYER_PID" ]] && kill -0 "$PLAYER_PID" 2>/dev/null; then
		kill -TERM "$PLAYER_PID" 2>/dev/null || true
		wait "$PLAYER_PID" 2>/dev/null || true
	fi
	PLAYER_PID=""
	WINDOW=""
}

cleanup() {
	stop_player
	if [[ -n "$XVFB_PID" ]] && kill -0 "$XVFB_PID" 2>/dev/null; then
		kill -TERM "$XVFB_PID" 2>/dev/null || true
		wait "$XVFB_PID" 2>/dev/null || true
	fi
}
trap cleanup EXIT INT TERM

wait_for() {
	local description=$1
	local attempts=$2
	shift 2
	for ((i = 0; i < attempts; i++)); do
		if "$@"; then
			return 0
		fi
		sleep 0.1
	done
	fail "timed out waiting for $description"
}

catalog_ready() {
	[[ -f "$DB" ]] && [[ $(sqlite3 "$DB" 'SELECT COUNT(*) FROM AUDIOBOOK_TABLE;' 2>/dev/null) == 2 ]]
}

parts_ready() {
	[[ $(sqlite3 "$DB" "SELECT COUNT(*) FROM AUDIOBOOK_PARTS WHERE book LIKE '%/Book One';" 2>/dev/null) == 2 ]]
}

checkpoint_ready() {
	local seconds
	seconds=$(sqlite3 "$DB" "SELECT resume_pos FROM AUDIOBOOK_TABLE WHERE name='Book One';" 2>/dev/null)
	awk -v seconds="$seconds" 'BEGIN { exit !(seconds >= 10) }'
}

details_ready() {
	[[ $(sqlite3 "$DB" "SELECT COUNT(*) FROM AUDIOBOOK_TABLE WHERE name='Book One' AND summary='Sidecar description & details.' AND series='Sidecar Cycle' AND series_part=2.5 AND path LIKE '%/Test Author/Series One/Book One';" 2>/dev/null) == 1 ]] &&
		[[ $(sqlite3 "$DB" "SELECT COUNT(*) FROM AUDIOBOOK_TABLE WHERE name='Standalone Book' AND summary='A host-test summary for the standalone M4B.' AND path LIKE '%/Standalone Author/Standalone Book/%';" 2>/dev/null) == 1 ]]
}

bookmark_ready() {
	[[ $(sqlite3 "$DB" 'SELECT COUNT(*) FROM AUDIOBOOK_BOOKMARKS;' 2>/dev/null) == 1 ]]
}

click() {
	printf 'tap %s %s 100\n' "$1" "$2" > "$FIFO"
	sleep "${3:-0.4}"
}

screenshot() {
	import -window "$WINDOW" "$WORK/$1.png"
}

start_player() {
	local run_name=$1
	local log="$WORK/$run_name.log"
	local stdout="$WORK/$run_name.stdout"

	(
		cd "$RUN"
		exec env \
			SONIX_SD_ROOT="$SD" \
			SONIX_CONTROL_FIFO="$FIFO" SONIX_CONTROL_STATUS="$STATUS" \
			SONIX_PANEL=480x800 SDL_VIDEODRIVER=x11 \
			SONIX_CONFIG="$CONFIG" \
			SONIX_EBOOK_CONFIG="$WORK/ebook_config.ini" \
			SONIX_LOG="$log" \
			ALSA_CONFIG_PATH="$ASOUND" \
			./sonix_player_host >"$stdout" 2>&1
	) &
	PLAYER_PID=$!

	wait_for "the simulator process" 30 kill -0 "$PLAYER_PID"
	for ((i = 0; i < 100; i++)); do
		WINDOW=$(xdotool search --onlyvisible --pid "$PLAYER_PID" 2>/dev/null | head -n 1 || true)
		[[ -n "$WINDOW" ]] && break
		sleep 0.1
	done
	[[ -n "$WINDOW" ]] || fail "the simulator window did not appear; see $stdout"
	sleep 1
}

for command in ffmpeg make import sqlite3 Xvfb xdotool; do
	need "$command"
done

# Upstream's Makefile passes its checkout path to GCC without shell quoting.
# Detect that limitation here so a developer gets a useful error instead of a
# page of broken -I arguments.
[[ "$ROOT" != *' '* ]] || fail "the checkout path contains spaces; move it before running the host build"

case "$WORK" in
	"$ROOT"/build/*) rm -rf -- "$WORK" ;;
	*) fail "refusing to replace an output directory outside $ROOT/build" ;;
esac
mkdir -p "$RUN/usr/resource" \
	"$SD/Audiobooks/Test Author/Series One/Book One" \
	"$SD/Audiobooks/Standalone Author/Standalone Book"

if [[ ${SONIX_SMOKE_SKIP_BUILD:-0} != 1 ]]; then
	make -C "$PLAYER" host -j2
fi
[[ -x "$PLAYER/sonix_player_host" ]] || fail "host binary is missing; run make -C sonix-player host"
cp "$PLAYER/sonix_player_host" "$RUN/"
cp -a "$ROOT/sonix-packer/assets/R1/usr/resource/." "$RUN/usr/resource/"

cat >"$CONFIG" <<EOF
# Generated by tools/audiobook-host-smoke.sh.
[player]
playback_mode = 0
volume = 40

[audio]
gapless = 1

[ui]
language = English

[clock]
utc_offset_minutes = 0
last_seen = $(date +%s)
configured = 1
EOF

cat >"$ASOUND" <<'EOF'
pcm.!default {
  type null
}
ctl.!default {
  type hw
  card 0
}
EOF

ffmpeg -hide_banner -loglevel error -f lavfi -i "sine=frequency=440:duration=30" \
	-ac 1 -b:a 64k -metadata album="Book One" -metadata album_artist="Test Author" \
	-metadata artist="Test Author" -metadata title="Part One" -metadata track="1/2" \
	-metadata comment="<p>A host-test <b>description</b> &amp; details.</p>" \
	"$SD/Audiobooks/Test Author/Series One/Book One/01 - Part One.mp3"
ffmpeg -hide_banner -loglevel error -f lavfi -i "sine=frequency=550:duration=60" \
	-ac 1 -b:a 64k -metadata album="Book One" -metadata album_artist="Test Author" \
	-metadata artist="Test Author" -metadata title="Part Two" -metadata track="2/2" \
	"$SD/Audiobooks/Test Author/Series One/Book One/02 - Part Two.mp3"
ffmpeg -hide_banner -loglevel error -f lavfi -i "sine=frequency=660:duration=60" \
	-ac 1 -c:a alac -metadata album="Standalone Book" \
	-metadata album_artist="Standalone Author" -metadata artist="Standalone Author" \
	-metadata title="Standalone Book" -metadata description="<p>A host-test summary for the standalone M4B.</p>" \
	"$SD/Audiobooks/Standalone Author/Standalone Book/Standalone Book.m4b"

# Sidecar metadata overrides embedded tags and reaches the real catalog.
first_part="$SD/Audiobooks/Test Author/Series One/Book One/01 - Part One.mp3"
printf 'series=Sidecar Cycle\nseries_part=2.5\n' > "$first_part.tags"
printf '<p>Sidecar <b>description</b> &amp; details.</p>\n' > "$first_part.description"

# Choose an unused local display; no network listener is needed.
Xvfb -nolisten tcp -ac -displayfd 3 -screen 0 480x800x24 \
	>"$WORK/xvfb.stdout" 2>"$WORK/xvfb.log" 3>"$DISPLAY_FILE" &
XVFB_PID=$!
wait_for "Xvfb display assignment" 50 test -s "$DISPLAY_FILE"
export DISPLAY=":$(cat "$DISPLAY_FILE")"

start_player first-run

# Actual GUI input through the same local control channel used over ADB.
wait_for "control FIFO" 50 test -p "$FIFO"
printf 'status\n' > "$FIFO"
wait_for "control status" 50 grep -q 'ok ready 480x800' "$STATUS"
click 356 440       # Home -> Audiobooks
click 240 584       # empty library -> Scan
wait_for "two scanned audiobooks" 300 catalog_ready
wait_for "two multipart rows" 50 parts_ready
wait_for "indexed descriptions" 50 details_ready
screenshot catalog
click 240 736       # scan result -> OK
click 124 246       # Library
click 240 180       # Book One
wait_for "multipart playback" 100 grep -q "01 - Part One.mp3" "$WORK/first-run.log"
xdotool key --window "$WINDOW" n
sleep 0.5
screenshot player
click 440 565       # save bookmark while paused
wait_for "one bookmark" 50 bookmark_ready
SAVED_BOOKMARK_POS=$(sqlite3 "$DB" 'SELECT pos FROM AUDIOBOOK_BOOKMARKS LIMIT 1;')
click 330 746       # advance ten seconds, still paused
printf 'tap 440 565 900\n' > "$FIFO"
sleep 1.5
screenshot bookmark-list
click 240 175       # return to bookmark
bookmark_seek_logged() {
 grep -oE 'seeking to [0-9]+\.[0-9]{2} seconds' "$WORK/first-run.log" | awk -v want="$SAVED_BOOKMARK_POS" \
  '{ if ($3 >= want - 0.0051 && $3 <= want + 0.0051) found = 1 } END { exit !found }'
}
wait_for "bookmark resume" 50 bookmark_seek_logged
click 330 746
click 330 746       # move close to the end of the 30-second first part
wait_for "persisted checkpoint" 100 checkpoint_ready
RESUME_POSITION=$(sqlite3 "$DB" "SELECT resume_pos FROM AUDIOBOOK_TABLE WHERE name='Book One';")
RESUME_FILE=$(sqlite3 "$DB" "SELECT resume_file FROM AUDIOBOOK_TABLE WHERE name='Book One';")
[[ "$RESUME_FILE" == *"01 - Part One.mp3" ]] || fail "wrong checkpoint part"
screenshot checkpoint
stop_player
start_player resume-run
click 356 440
click 356 440       # Continue tile
click 240 180
resume_logged() {
 grep -F "restore requested '$RESUME_FILE'" "$WORK/resume-run.log" | \
  sed -n 's/.* at \([0-9.]*\) s (paused).*/\1/p' | \
  awk -v want="$RESUME_POSITION" '{if ($1 >= want - 0.11 && $1 <= want + 0.11) found=1} END {exit !found}'
}
wait_for "exact direct resume after restart" 100 resume_logged
bookmark_ready || fail "bookmark lost on restart"
screenshot resumed
wait_for "multipart auto-advance" 200 grep -q "starting '.*02 - Part Two.mp3'" "$WORK/resume-run.log"
grep -q "gapless: reusing the open PCM" "$WORK/resume-run.log" || fail "gapless PCM closed"
printf 'PASS GUI catalog, descriptions, bookmark, restart resume, gapless auto-advance, FIFO input\n'
printf 'Resume: %s at %s seconds\nArtifacts: %s\n' "$RESUME_FILE" "$RESUME_POSITION" "$WORK"
